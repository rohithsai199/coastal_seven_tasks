export const useStorefrontStore = create(
  persist(
    (set) => ({
      config: DEFAULT_STOREFRONT_CONFIG,

      updateSection: (sectionKey, updates) =>
        set((state) => ({
          config: {
            ...state.config,
            [sectionKey]: {
              ...state.config[sectionKey],
              ...updates,
            },
          },
        })),

      updateLook: (sectionKey, lookIndex, lookUpdates) =>
        set((state) => {
          const currentSection = state.config[sectionKey] || {};
          const currentLooks =
            currentSection.looks && currentSection.looks.length > 0
              ? currentSection.looks.map((l) => ({ ...l }))
              : JSON.parse(
                  JSON.stringify(DEFAULT_STOREFRONT_CONFIG[sectionKey]?.looks || [])
                );

          currentLooks[lookIndex] = {
            ...currentLooks[lookIndex],
            ...lookUpdates,
          };

          return {
            config: {
              ...state.config,
              [sectionKey]: {
                ...currentSection,
                looks: currentLooks,
              },
            },
          };
        }),

      resetSection: (sectionKey) =>
        set((state) => ({
          config: {
            ...state.config,
            [sectionKey]: JSON.parse(
              JSON.stringify(DEFAULT_STOREFRONT_CONFIG[sectionKey])
            ),
          },
        })),

      resetAll: () =>
        set(() => ({
          config: JSON.parse(JSON.stringify(DEFAULT_STOREFRONT_CONFIG)),
        })),
    }),
    {
      name: "arise_storefront_cms_v4",
    }
  )
);
